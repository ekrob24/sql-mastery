#!/usr/bin/env python3
"""Generate snowflake/setup/*.sql from sql_mastery.db so Snowflake gets identical data."""
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "snowflake" / "setup"

TABLES = {
    "customers": "customer_id INTEGER PRIMARY KEY, name VARCHAR, email VARCHAR, signup_date DATE, region VARCHAR",
    "suppliers": "supplier_id INTEGER PRIMARY KEY, supplier_name VARCHAR, country VARCHAR",
    "products": "product_id INTEGER PRIMARY KEY, product_name VARCHAR, category VARCHAR, list_price NUMBER(10,2), supplier_id INTEGER",
    "orders": "order_id INTEGER PRIMARY KEY, customer_id INTEGER, order_date DATE, order_status VARCHAR",
    "order_items": "order_item_id INTEGER PRIMARY KEY, order_id INTEGER, product_id INTEGER, quantity INTEGER, unit_price NUMBER(10,2)",
    "returns": "return_id INTEGER PRIMARY KEY, order_item_id INTEGER, return_date DATE, return_reason VARCHAR, refund_amount NUMBER(10,2)",
    "product_costs": "product_id INTEGER PRIMARY KEY, unit_cost NUMBER(10,2)",
    "categories": "category_id INTEGER PRIMARY KEY, category_name VARCHAR, parent_category_id INTEGER",
    "web_events": "event_id INTEGER PRIMARY KEY, session_id VARCHAR, customer_id INTEGER, event_type VARCHAR, event_time TIMESTAMP_NTZ, product_id INTEGER",
    "raw_order_events": "event_id INTEGER PRIMARY KEY, received_at TIMESTAMP_NTZ, payload VARIANT",
}

PLATFORM = """-- SQL Mastery: warehouse, database and schemas. Runs as role SQL_MASTERY_DEV.
CREATE WAREHOUSE IF NOT EXISTS SQL_MASTERY_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'SQL Mastery practice';
CREATE DATABASE IF NOT EXISTS SQL_MASTERY COMMENT = 'SQL Mastery: practice warehouse + app';
CREATE SCHEMA IF NOT EXISTS SQL_MASTERY.SHOP COMMENT = 'The e-commerce practice data (rebuilt on every install)';
CREATE SCHEMA IF NOT EXISTS SQL_MASTERY.APP  COMMENT = 'Progress tables and app files (never wiped)';
CREATE STAGE IF NOT EXISTS SQL_MASTERY.APP.APP_STAGE DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'SQL Mastery app files (copied from the GitHub repo by install.sql)';
"""

APP_TABLES = """-- Progress storage. CREATE IF NOT EXISTS: reinstalling never erases your progress.
CREATE TABLE IF NOT EXISTS SQL_MASTERY.APP.PROGRESS (
    exercise_key     VARCHAR PRIMARY KEY,   -- e.g. '10.3'
    status           VARCHAR,               -- attempted | needs_explanation | completed
    attempts         INTEGER DEFAULT 0,
    hints_revealed   INTEGER DEFAULT 0,
    solution_viewed  BOOLEAN DEFAULT FALSE,
    explanation      VARCHAR,
    last_sql         VARCHAR,
    first_attempt_at TIMESTAMP_NTZ,
    completed_at     TIMESTAMP_NTZ,
    updated_at       TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS SQL_MASTERY.APP.SUBMISSIONS (
    submitted_at  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    exercise_key  VARCHAR,
    passed        BOOLEAN,
    plan_ok       BOOLEAN,
    message       VARCHAR,
    sql_text      VARCHAR
);
CREATE TABLE IF NOT EXISTS SQL_MASTERY.APP.CHECKPOINTS (
    checkpoint    VARCHAR PRIMARY KEY,      -- 'joins'
    passed        BOOLEAN,
    attempts      INTEGER,
    passed_at     TIMESTAMP_NTZ,
    last_results  VARIANT
);
"""


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    conn = sqlite3.connect(ROOT / "sql_mastery.db")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "00_platform.sql").write_text(PLATFORM, encoding="utf-8")
    ddl = ["-- Practice tables (Snowflake types). Generated by tools/export_snowflake.py — do not edit.",
           "USE SCHEMA SQL_MASTERY.SHOP;"]
    data = ["-- Practice data, identical to sql_mastery.db. Generated by tools/export_snowflake.py — do not edit.",
            "USE SCHEMA SQL_MASTERY.SHOP;"]
    for t, cols in TABLES.items():
        ddl.append(f"CREATE OR REPLACE TABLE {t} ({cols});")
        names = [c.strip().split()[0] for c in cols.split(",") if c.strip() and not c.strip()[0].isdigit()]
        rows = conn.execute(f"SELECT {', '.join(names)} FROM {t} ORDER BY 1").fetchall()
        vals = ",\n".join("(" + ", ".join(lit(v) for v in r) + ")" for r in rows)
        if t == "raw_order_events":
            data.append(f"INSERT INTO {t} SELECT column1, column2::TIMESTAMP_NTZ, PARSE_JSON(column3) FROM VALUES\n{vals};")
        else:
            data.append(f"INSERT INTO {t} ({', '.join(names)}) VALUES\n{vals};")
    (OUT / "10_tables.sql").write_text("\n".join(ddl) + "\n", encoding="utf-8")
    (OUT / "20_data.sql").write_text("\n\n".join(data) + "\n", encoding="utf-8")
    (OUT / "30_app_tables.sql").write_text(APP_TABLES, encoding="utf-8")
    print("wrote", ", ".join(p.name for p in sorted(OUT.glob("*.sql"))))


if __name__ == "__main__":
    sys.exit(main())
