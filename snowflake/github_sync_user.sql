-- Run ONCE in Snowsight after install.sql, to let the GitHub Action snapshot your progress.
-- Creates a read-only service user. Copy token_secret from the last result into the GitHub repo
-- secret SNOWFLAKE_TOKEN (repo » Settings » Secrets and variables » Actions). Never paste it anywhere else.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS SQL_MASTERY_SYNC;
GRANT USAGE ON WAREHOUSE SQL_MASTERY_WH TO ROLE SQL_MASTERY_SYNC;
GRANT USAGE ON DATABASE SQL_MASTERY TO ROLE SQL_MASTERY_SYNC;
GRANT USAGE ON SCHEMA SQL_MASTERY.APP TO ROLE SQL_MASTERY_SYNC;
GRANT SELECT ON ALL TABLES IN SCHEMA SQL_MASTERY.APP TO ROLE SQL_MASTERY_SYNC;

CREATE USER IF NOT EXISTS SQL_MASTERY_SYNC_USER
  TYPE = SERVICE DEFAULT_ROLE = SQL_MASTERY_SYNC DEFAULT_WAREHOUSE = SQL_MASTERY_WH
  COMMENT = 'Read-only: GitHub Action that snapshots SQL Mastery progress';
GRANT ROLE SQL_MASTERY_SYNC TO USER SQL_MASTERY_SYNC_USER;

-- GitHub's runners have no fixed IP, so this token can't be tied to a network policy.
CREATE DATABASE IF NOT EXISTS SQL_MASTERY_ADMIN;
CREATE SCHEMA IF NOT EXISTS SQL_MASTERY_ADMIN.POLICIES;
CREATE AUTHENTICATION POLICY IF NOT EXISTS SQL_MASTERY_ADMIN.POLICIES.SQL_MASTERY_PAT_POLICY
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED);
ALTER USER SQL_MASTERY_SYNC_USER SET AUTHENTICATION POLICY SQL_MASTERY_ADMIN.POLICIES.SQL_MASTERY_PAT_POLICY;

ALTER USER SQL_MASTERY_SYNC_USER ADD PROGRAMMATIC ACCESS TOKEN GITHUB_SNAPSHOT
  ROLE_RESTRICTION = 'SQL_MASTERY_SYNC'
  DAYS_TO_EXPIRY = 90;
